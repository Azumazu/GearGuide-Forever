#!/usr/bin/env python3
"""
Generates GearGuide/SpecWeights.lua from the researched stat weights in spec_weights/<CLASS>.json.

Each JSON file holds, per spec: a stat priority list, numeric weights (value per point, per 1% for
percent stats), optional leveling overrides, caps, confidence, notes and sources. Edit the JSON
(e.g. after a balance patch), then run:  python gen_spec_weights.py
"""
from __future__ import annotations

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from update_db import lua_str, lua_val  # noqa: E402

SRC = HERE / "spec_weights"
OUT = HERE.parent / "GearGuide" / "SpecWeights.lua"
STAT_KEYS = {"STR", "AGI", "STA", "INT", "SPI", "ARMOR", "DPS", "AP", "RAP", "SP", "HEAL",
             "CRIT", "HIT", "SCRIT", "SHIT", "HASTE", "EXPERTISE", "RDPS", "DEF", "DODGE", "PARRY", "BLOCK", "MP5"}
EXPECTED = {
    "WARRIOR": ["ARMS", "FURY", "PROTECTION"], "PALADIN": ["HOLY", "PROTECTION", "RETRIBUTION"],
    "HUNTER": ["BEASTMASTERY", "MARKSMANSHIP", "SURVIVAL"], "ROGUE": ["ASSASSINATION", "COMBAT", "SUBTLETY"],
    "PRIEST": ["DISCIPLINE", "HOLY", "SHADOW"], "SHAMAN": ["ELEMENTAL", "ENHANCEMENT", "RESTORATION"],
    "MAGE": ["ARCANE", "FIRE", "FROST"], "WARLOCK": ["AFFLICTION", "DEMONOLOGY", "DESTRUCTION"],
    "DRUID": ["BALANCE", "FERAL_CAT", "FERAL_BEAR", "RESTORATION"],
}


def clean_weights(table: dict, where: str, problems: list[str]) -> dict:
    out = {}
    for k, v in (table or {}).items():
        if k not in STAT_KEYS:
            problems.append(f"{where}: unknown stat key {k!r} (ignored)")
        elif not isinstance(v, (int, float)) or v < 0:
            problems.append(f"{where}: bad weight {k}={v!r} (ignored)")
        else:
            out[k] = round(float(v), 3)
    return out


def main() -> int:
    problems: list[str] = []
    lines = [
        "-- GENERATED by GearGuideTools/gen_spec_weights.py from GearGuideTools/spec_weights/*.json.",
        "-- Stat weights per specialization, researched from WoW: Forever class guides (sources per spec below).",
        f"-- Generated {datetime.now(timezone.utc).strftime('%Y-%m-%d')}. Edit the JSON, not this file.",
        "local _, ns = ...",
        "ns.SPEC_WEIGHTS = {}",
        "local W = ns.SPEC_WEIGHTS",
    ]
    for cls, specs in EXPECTED.items():
        path = SRC / f"{cls}.json"
        if not path.exists():
            problems.append(f"{cls}: {path.name} missing (class keeps the built-in role weights)")
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        lines.append(f"W.{cls} = {{}}")
        for spec in specs:
            entry = (data.get("specs") or {}).get(spec)
            if not entry:
                problems.append(f"{cls}.{spec}: missing (keeps built-in role weights)")
                continue
            weights = clean_weights(entry.get("weights"), f"{cls}.{spec}", problems)
            if not weights:
                problems.append(f"{cls}.{spec}: no usable weights")
                continue
            leveling = clean_weights(entry.get("leveling"), f"{cls}.{spec}.leveling", problems)
            priority = [p for p in entry.get("priority") or [] if p in STAT_KEYS]
            for src in entry.get("sources") or []:
                lines.append(f"-- {cls}.{spec}: {src.get('url', '?')} ({src.get('date_or_status', '?')})")
            record = {"weights": weights, "priority": priority,
                      "confidence": entry.get("confidence") or "unknown"}
            if leveling:
                record["leveling"] = leveling
            if entry.get("caps"):
                record["caps"] = [str(c) for c in entry["caps"]]
            lines.append(f"W.{cls}.{spec} = {lua_val(record)}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT}")
    for p in problems:
        print("  note:", p)
    return 0


if __name__ == "__main__":
    sys.exit(main())
